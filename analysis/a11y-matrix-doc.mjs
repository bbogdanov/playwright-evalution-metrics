/**
 * Regenerates the matrix table inside docs/ACCESSIBILITY-AND-TEST-LEVELS.md from
 * the same data the Accessibility page renders.
 *
 * The table used to be written by hand, and it had already drifted from the page
 * by one verdict. A document and a published page that disagree about a
 * recommendation are worse than either alone, so only one of them is authored.
 *
 * Only the region between the markers is touched; the surrounding argument stays
 * hand-written, because it is an argument.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';
import { LEVELS, ROWS } from './a11y-matrix.mjs';

const DOC = resolve('docs/ACCESSIBILITY-AND-TEST-LEVELS.md');
const START = '<!-- matrix:start -->';
const END = '<!-- matrix:end -->';

/**
 * The opening of the reasoning, which is where the verdict is justified.
 *
 * Sentences are taken until there are enough of them to be worth reading: several
 * cells open with "Avoid." or "Harmless.", which is a verdict restated rather
 * than a reason. The full text belongs on the page, where a cell can be clicked;
 * a markdown table holding four paragraphs per row is not a table anyone reads.
 */
const MIN_LEAD = 90;

/**
 * Splits prose into sentences without splitting decimals.
 *
 * A terminator only ends a sentence when what follows is the end of the text or
 * whitespace and then a capital. Without that, "about 1.7 ms" becomes two
 * sentences and the table quotes half a number.
 */
function sentences(text) {
  const out = [];
  let start = 0;
  for (let i = 0; i < text.length; i++) {
    if (!'.!?'.includes(text[i])) continue;
    const rest = text.slice(i + 1);
    if (rest !== '' && !/^\s+["\u201c'(]?[A-Z]/.test(rest)) continue;
    out.push(text.slice(start, i + 1).trim());
    start = i + 1;
  }
  if (start < text.length) out.push(text.slice(start).trim());
  return out.filter(Boolean);
}

function lead(why) {
  let out = '';
  for (const s of sentences(why)) {
    out += (out ? ' ' : '') + s;
    if (out.length >= MIN_LEAD) break;
  }
  return out;
}

const cell = (c) =>
  `**${c.verdict === 'yes' ? 'Yes' : 'No'}** — ${lead(c.why).replace(/\|/g, '\\|')}`;

const table = [
  `| Locator | ${LEVELS.map((l) => l.title).join(' | ')} |`,
  `|---|${LEVELS.map(() => '---').join('|')}|`,
  ...ROWS.map(
    (r) =>
      `| \`${r.label}\` | ` +
      LEVELS.map((l) => (r.cells[l.id] ? cell(r.cells[l.id]) : '—')).join(' | ') +
      ' |',
  ),
].join('\n');

const doc = readFileSync(DOC, 'utf8');
const i = doc.indexOf(START);
const j = doc.indexOf(END);
if (i < 0 || j < 0) {
  console.error(`No ${START} / ${END} markers in ${DOC}.`);
  process.exit(1);
}

const body =
  `${START}\n` +
  '<!-- Generated by analysis/a11y-matrix-doc.mjs from analysis/a11y-matrix.mjs. Edit that. -->\n\n' +
  `${table}\n\n` +
  'Each cell above is the opening of a longer explanation. The full reasoning, with\n' +
  'a code example per cell, is on the generated Accessibility page.\n\n' +
  END;

writeFileSync(DOC, doc.slice(0, i) + body + doc.slice(j + END.length));
console.log(`Updated the matrix in ${DOC} (${ROWS.length} locators x ${LEVELS.length} levels)`);
